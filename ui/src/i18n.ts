export type MessageKey = keyof typeof en;

export type MessageParams = Record<string, string | number>;

/** Whether `key` is a message of this file, for a check of a key that came from elsewhere. */
export function hasMessage(key: string): key is MessageKey {
  return Object.hasOwn(en, key);
}

/**
 * The message for `key` with its `{name}`s filled in. A `{reason}` is the text of an error, which
 * the catalogue always puts in brackets, inside a sentence with a full stop of its own: so the
 * one the error may end with is dropped.
 */
export function t(key: MessageKey, params: MessageParams = {}): string {
  return en[key].replace(/\{(\w+)\}/g, (whole, name: string) => {
    if (!(name in params)) return whole;
    const value = String(params[name]);
    return name === "reason" ? value.replace(/[.\s]+$/, "") : value;
  });
}
